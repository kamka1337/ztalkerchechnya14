using Content.Client.Message;
using Content.Client.UserInterface.Systems.EscapeMenu;
using Robust.Client.AutoGenerated;
using Robust.Client.Console;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Lobby.UI
{
    [GenerateTypedNameReferences]
    public sealed partial class LobbyGui : UIScreen
    {
        [Dependency] private readonly IClientConsoleHost _consoleHost = default!;

        public LobbyGui()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);

            LayoutContainer.SetAnchorPreset(Background, LayoutPreset.Wide);
            LayoutContainer.SetAnchorPreset(MainContainer, LayoutPreset.Wide);

            LayoutContainer.SetAnchorPreset(DefaultState, LayoutPreset.Wide);
            LayoutContainer.SetAnchorPreset(CharacterSetupState, LayoutPreset.Wide);

            UpdateRightPanelLayout();

            LayoutContainer.SetAnchorPreset(ExpandPanel, LayoutPreset.TopRight);
            LayoutContainer.SetGrowHorizontal(ExpandPanel, LayoutContainer.GrowDirection.Begin);
            LayoutContainer.SetMarginRight(ExpandPanel, -10);
            LayoutContainer.SetMarginTop(ExpandPanel, 10);

            LobbySong.SetMarkup(Loc.GetString("lobby-state-song-no-song-text"));

            LeaveButton.OnPressed += _ => _consoleHost.ExecuteCommand("disconnect");
            OptionsButton.OnPressed += _ => UserInterfaceManager.GetUIController<OptionsUIController>().ToggleWindow();

            CollapseButton.OnPressed += _ => TogglePanel(false);
            ExpandButton.OnPressed += _ => TogglePanel(true);
        }

        public void UpdateRightPanelLayout(float? width = null)
        {
            var panelWidth = width ?? (float.IsNaN(RightSide.SetWidth) ? 460f : RightSide.SetWidth);
            if (panelWidth <= 0)
                panelWidth = 460f;

            LayoutContainer.SetAnchorPreset(RightSide, LayoutPreset.RightWide);
            LayoutContainer.SetGrowHorizontal(RightSide, LayoutContainer.GrowDirection.Begin);
            LayoutContainer.SetMarginRight(RightSide, -10);
            LayoutContainer.SetMarginLeft(RightSide, -(panelWidth + 10));
            LayoutContainer.SetMarginTop(RightSide, 10);
            LayoutContainer.SetMarginBottom(RightSide, -10);
        }

        public void SwitchState(LobbyGuiState state)
        {
            DefaultState.Visible = true;
            CharacterSetupState.Visible = false;
            RightSide.Visible = true;
            ExpandPanel.Visible = false;
        }

        private void TogglePanel(bool value)
        {
            RightSide.Visible = value;
            ExpandPanel.Visible = !value;
        }

        public enum LobbyGuiState : byte
        {
            /// <summary>
            ///  The default state, i.e., what's seen on launch.
            /// </summary>
            Default,
            /// <summary>
            ///  The character setup state.
            /// </summary>
            CharacterSetup
        }
    }
}
